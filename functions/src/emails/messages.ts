const MESSAGES: Record<Locale, EmailMessages> = { en, ro, de };
export const emailMessages = (locale: Locale) => MESSAGES[locale];

// Fills in the {placeholders} of a text
export const fill = (text: string, params: Record<string, string | number> = {}) => text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
